% 4. LMI 
% ==========================================
s11 = A*Q + Q*A' - B*Y - Y'*B' + alpha*Q;
s12 = delta * D_e;
s22 = -eye(n_f);

LMI = [s11, s12; s12', s22];
cons = [LMI <= 0, Q >= 0];

sol = optimize(cons); %[output:35d52370]

